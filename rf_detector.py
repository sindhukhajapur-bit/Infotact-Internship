"""RF anomaly and covert channel detector: per-bin baseline fingerprinting, narrowband clustering, and modulation classification."""
from collections import deque
from typing import Dict, Any, List
import numpy as np
from scipy import ndimage

from models import Finding


class RFDetector:
    """Radio Frequency spectrum anomaly detector.

    Detects covert radio frequency emissions (such as those generated by CPU memory buses,
    GPU lines, or USB cables via malware like AirHopper or GSMem) by establishing a per-bin
    statistical baseline and classifying spectral excursions.

    Detection steps:
      1. Baseline fingerprint: Learns mean and variance for each frequency bin across N calibration sweeps.
      2. Adaptive thresholding: Per-bin threshold = mean + max(threshold_db, sigma * std).
      3. Window buffer: Evaluates persistence across a sliding history of sweeps.
      4. Morphological clustering: Groups contiguous active bins into discrete emitter objects.
      5. Classification: Discriminates wideband interference from narrowband carriers and keyed modulations.
    """

    def __init__(self, settings, origin: str = "simulated"):
        self.s = settings
        self.origin = origin
        self._cal = []
        self.mean = None
        self.std = None
        self.threshold = None
        self.window = deque(maxlen=settings.rf_window)

    @property
    def calibrated(self) -> bool:
        return self.mean is not None

    @property
    def calibration_progress(self) -> tuple:
        return min(len(self._cal), self.s.rf_calibration_sweeps), self.s.rf_calibration_sweeps

    def reset(self):
        self._cal = []
        self.mean = None
        self.std = None
        self.threshold = None
        self.window.clear()

    def process(self, freqs: np.ndarray, power: np.ndarray) -> Dict[str, Any]:
        """Processes 1 RF spectral sweep (frequencies in MHz, power in dB)."""
        freqs = np.asarray(freqs, dtype=float)
        power = np.asarray(power, dtype=float)

        res = {
            "freqs": freqs,
            "power": power,
            "status": "calibrating" if not self.calibrated else "monitoring",
            "findings": [],
            "baseline": self.mean,
            "threshold": self.threshold,
            "exceed_mask": np.zeros(power.size, dtype=bool)
        }

        # Step 1: Calibration
        if not self.calibrated:
            self._cal.append(power)
            if len(self._cal) >= self.s.rf_calibration_sweeps:
                arr = np.vstack(self._cal)
                self.mean = arr.mean(axis=0)
                self.std = np.maximum(arr.std(axis=0), 1.0)
                self.threshold = self.mean + np.maximum(self.s.rf_threshold_db, self.s.rf_sigma * self.std)
                res["status"] = "monitoring"
            res.update(baseline=self.mean, threshold=self.threshold)
            return res

        # Step 2: Monitoring & Thresholding
        res["status"] = "monitoring"
        res["baseline"] = self.mean
        res["threshold"] = self.threshold
        exceed_mask = power > self.threshold
        res["exceed_mask"] = exceed_mask

        self.window.append(power)
        if len(self.window) < self.s.rf_min_window:
            return res

        P = np.vstack(self.window)
        exceed = P > self.threshold
        activity = exceed.mean(axis=0)
        # Bins must exceed threshold at least 2 times, have >= 12% activity, and be active recently
        candidates = (exceed.sum(axis=0) >= 2) & (activity >= 0.12) & exceed[-5:].any(axis=0)
        if not candidates.any():
            return res

        # Cluster contiguous candidate bins
        labels, n_labels = ndimage.label(ndimage.binary_dilation(candidates, iterations=1))
        bin_khz = float(np.mean(np.diff(freqs))) * 1000.0

        for label_idx in range(1, n_labels + 1):
            idx = np.where((labels == label_idx) & candidates)[0]
            if idx.size == 0:
                continue

            center_bin = int(idx[np.argmax(P[:, idx].mean(axis=0))])
            bin_series = exceed[:, center_bin]
            duty = float(bin_series.mean())
            transitions = int(np.count_nonzero(np.diff(bin_series.astype(int))))
            width_khz = float((idx.max() - idx.min() + 1) * bin_khz)
            peak_db = float(P[:, center_bin].max())
            excess_db = peak_db - float(self.mean[center_bin])
            fmhz = float(freqs[center_bin])

            finding = self._classify_emitter(fmhz, peak_db, excess_db, width_khz, duty, transitions, len(P))
            res["findings"].append(finding)

        return res

    def _classify_emitter(self, fmhz: float, peak_db: float, excess_db: float,
                          width_khz: float, duty: float, transitions: int, wlen: int) -> Finding:
        """Classifies detected RF spectral excursion into security categories."""
        details = {
            "freq_mhz": round(fmhz, 4),
            "peak_db": round(peak_db, 1),
            "excess_over_baseline_db": round(excess_db, 1),
            "width_khz": round(width_khz, 1),
            "duty_cycle": round(duty, 2),
            "transitions": transitions,
            "window_sweeps": wlen
        }

        base_conf = int(min(90, 45 + excess_db))

        # Check 1: Wideband rise (> threshold kHz) -> Environmental or switching interference
        if width_khz > self.s.rf_max_narrowband_khz:
            return Finding(
                source="RF",
                origin=self.origin,
                kind="rf_wideband_rise",
                threat_category="Environmental RF Noise",
                severity="Low",
                confidence=35,
                summary=(f"Wideband RF elevation observed near {fmhz:.3f} MHz ({width_khz:.0f} kHz bandwidth, "
                         f"+{excess_db:.1f} dB). Characteristic of switching power supplies or electrical noise."),
                details=details,
                freq=fmhz,
                freq_tol=0.1
            )

        # Check 2: On-Off Keyed Narrowband Emitter -> Potential AirHopper/GSMem emanation
        if transitions >= 3 and 0.12 <= duty <= 0.88:
            return Finding(
                source="RF",
                origin=self.origin,
                kind="rf_keyed_emitter",
                threat_category="Modulated RF Carrier",
                severity="High",
                confidence=min(95, base_conf + 18),
                summary=(f"New pulsed narrowband RF emitter at {fmhz:.3f} MHz switching on/off "
                         f"({transitions} transitions, {duty*100:.0f}% duty cycle, +{excess_db:.0f} dB above baseline). "
                         "Pattern matches intentional On-Off Keying (OOK) radio exfiltration."),
                details=details,
                freq=fmhz,
                freq_tol=0.02
            )

        # Check 3: Continuous Narrowband Carrier -> New transmitter or local unmodulated clock
        if duty >= 0.75:
            return Finding(
                source="RF",
                origin=self.origin,
                kind="rf_new_carrier",
                threat_category="Anomalous RF Carrier",
                severity="Medium",
                confidence=base_conf,
                summary=(f"New continuous narrowband carrier observed at {fmhz:.3f} MHz "
                         f"(+{excess_db:.0f} dB above calibrated baseline). Possible unauthorized device or active carrier."),
                details=details,
                freq=fmhz,
                freq_tol=0.02
            )

        # Check 4: Intermittent Low-Activity Emitter
        return Finding(
            source="RF",
            origin=self.origin,
            kind="rf_intermittent_emitter",
            threat_category="Intermittent RF Emission",
            severity="Low",
            confidence=max(30, base_conf - 15),
            summary=(f"Intermittent narrowband RF burst observed at {fmhz:.3f} MHz ({duty*100:.0f}% duty cycle). "
                     "Transient emanation below sustained attack threshold."),
            details=details,
            freq=fmhz,
            freq_tol=0.02
        )
